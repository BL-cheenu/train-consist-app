/**
 * Sub-classification for PASSENGER bogies.
 * Defines the class of service offered inside the coach.
 */
public enum PassengerSubType {

    /** Berth-based overnight travel coach. */
    SLEEPER,

    /** Reclining chair car — used for medium-distance day travel. */
    AC_CHAIR,

    /** Premium class with individual compartments and higher capacity cost. */
    FIRST_CLASS
}
